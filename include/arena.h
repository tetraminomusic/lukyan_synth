/**
 * @file arena.h
 * @brief Статический аллокатор памяти для Real-Time систем.
 *
 * Предоставляет простой, быстрый и предсказуемый механизм выделения памяти
 * без вызова стандартного malloc. Все выделения происходят линейно из
 * заранее зарезервированного буфера.
 */

#ifndef ARENA_H
#define ARENA_H

#include <stddef.h>
#include <stdint.h>

/**
 * @brief Структура-дескриптор арены памяти.
 */
typedef struct {
    uint8_t *buffer;    /**< Указатель на начало буфера памяти. */
    size_t capacity;    /**< Общий размер буфера в байтах. */
    size_t offset;      /**< Текущее смещение (сколько байт занято). */
} MemoryArena;

/**
 * @brief Инициализирует арену, привязывая её к буферу памяти.
 * @param arena    Указатель на структуру арены.
 * @param raw_memory Указатель на сырой буфер памяти.
 * @param capacity Размер буфера в байтах.
 */
void arena_init(MemoryArena *arena, void *raw_memory, size_t capacity);

/**
 * @brief Выделяет блок памяти указанного размера.
 *
 * Размер автоматически выравнивается до 8 байт для корректной работы
 * процессора с любыми типами данных. При переполнении возвращает NULL.
 *
 * @param arena Указатель на структуру арены.
 * @param size  Запрашиваемый размер в байтах.
 * @return Указатель на выделенную память или NULL при переполнении.
 */
void *arena_alloc(MemoryArena *arena, size_t size);

/**
 * @brief Сбрасывает арену, освобождая всю выделенную память.
 *
 * Не выполняет никаких операций с памятью, просто сбрасывает смещение в 0.
 *
 * @param arena Указатель на структуру арены.
 */
void arena_reset(MemoryArena *arena);

#endif