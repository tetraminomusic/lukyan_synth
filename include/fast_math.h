/**
 * @file fast_math.h
 * @brief Быстрые математические функции для использования в аудиопотоке.
 *
 * Заменяют медленные функции из стандартной библиотеки libm на быстрые
 * полиномиальные аппроксимации.
 */

#ifndef FAST_MATH_H
#define FAST_MATH_H

#include <stdint.h>

/**
 * @brief Быстрая аппроксимация гиперболического тангенса для софт-клиппа.
 *
 * Использует кубический рациональный полином вместо вызова функции tanhf() из libm
 * 
 * @param x Входное значение (любое).
 * @return Значение tanh(x), ограниченное диапазоном [-1, 1].
 */

float fast_tanhf(float x);

/**
 * @brief Расчёт степени двойки.
 *
 * Используется для преобразования полутонов в коэффициент частоты.
 *
 * @param p Показатель степени.
 * @return Результат 2^p.
 */
float fast_pow2(float p);

#endif